import postgres from 'npm:postgres@3.4.5';
import { createEngine } from '../supabase/functions/api/engine.js';
import { ensureSchema } from '../supabase/functions/api/bootstrap.js';
import { memoryStorage, testSms } from '../supabase/functions/api/adapters.js';
import { createHandler, once } from '../supabase/functions/api/server.js';
import seed from '../supabase/functions/api/seed.js';
const sql = postgres('postgres://postgres:pw@127.0.0.1:54329/sbp_deno', { prepare: false, max: 3, onnotice: () => {} });
const storage = memoryStorage(), sms = testSms(true);
const engine = createEngine({ sql, storage, sms });
const ready = once(async () => { await ensureSchema(sql, { SCHEMA: engine.SCHEMA, seed, defaults: engine.core._t.DEFAULT_SETTINGS, nowIso: engine.core._t.nowIso }); });
const handle = createHandler({ engine, ready });
const call = async (fn, ...args) => (await (await handle(new Request('http://x/', { method: 'POST', headers: { 'content-type': 'application/json', origin: 'https://sbp.pages.dev' }, body: JSON.stringify({ fn, args }) }))).json()).value;
const code = (await Deno.readTextFile(new URL('../.setup-code.txt', import.meta.url))).trim();
console.log('status', JSON.stringify(await call('publicStatus')));
const st = await call('setupInit', code, '0810000001');
console.log('setup', st.ok, st.data && st.data.user.name);
const otp = await call('otpRequest', '0810000001');
const c = /: (\d{6}) /.exec(sms.box[0].text)[1];
const v = await call('otpVerify', '0810000001', c);
console.log('otp login', otp.ok, v.ok);
const tok = v.data.token;
const lead = await call('api', tok, 'leads.save', { cust_id: 'C0002', cust_name: 'x', site: 'ตึก A', job_type: 'ล้าง', units: 2, answers: { type: 'ติดผนัง', qty: '2', access: 'ชั้น 1', symptom: 'ล้าง' } });
const q = await call('api', tok, 'quotes.save', { lead_id: lead.data.lead_id, payment: 'เงินสด', lines: [{ item_id: 'CL-0001', qty: 8 }] });
console.log('quote', q.ok, q.data && q.data.net);
const ph = await call('api', tok, 'leads.photo', { lead_id: lead.data.lead_id, data: 'data:image/jpeg;base64,' + btoa('abc') });
console.log('photo', ph.ok, storage._map.size);
const d = await call('api', tok, 'dashboard', {});
console.log('dashboard', d.ok, d.error || '');
const cnt = await sql`select count(*)::int n from sbp.catalog`;
console.log('catalog rows', cnt[0].n);
await sql.end();
